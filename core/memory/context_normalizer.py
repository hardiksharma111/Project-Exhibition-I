"""
Universal Context Envelope (UCE) Architecture
Cross-Model Context Normalization & Canonical Dialogue Units (CDU)
Prevents formatting breakdown across model switches (Gemma <-> Qwen <-> Llama).
"""

import re
import time
import uuid
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

# Model-specific artifact cleanup regex
SPECIAL_TOKENS_REGEX = re.compile(
    r"(<\|im_start\|>|<\|im_end\|>|<\|eot_id\|>|<\|start_header_id\|>|<\|end_header_id\|>|"
    r"<start_of_turn>|<end_of_turn>|\[INST\]|\[/INST\]|<s>|</s>|<pad>|<unk>)",
    re.IGNORECASE
)


class CanonicalDialogueUnit(BaseModel):
    """
    Model-invariant representation of a single conversational interaction.
    """
    cdu_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    role: str = Field(..., description="user | assistant | system")
    content: str = Field(..., description="Sanitized semantic payload")
    source_model: str = Field(..., description="Model that produced or processed this unit")
    domain: str = Field(..., description="Domain under which this turn occurred")
    timestamp: float = Field(default_factory=time.time)
    importance_weight: float = Field(1.0, description="Semantic salience [0.0 - 1.0]")
    extracted_facts: List[str] = Field(default_factory=list, description="Extracted key assertions")


class UniversalContextEnvelope:
    """
    Manages and compiles context across disparate SLM tokenizers and prompt structures.
    Formats canonical dialogue units into model-specific chat templates.
    """

    @staticmethod
    def sanitize(text: str) -> str:
        """Strips proprietary prompt markers to prevent prompt injection or tokenizer glitching."""
        cleaned = SPECIAL_TOKENS_REGEX.sub("", text)
        return cleaned.strip()

    @staticmethod
    def create_cdu(role: str, content: str, source_model: str, domain: str,
                   importance: float = 1.0, facts: Optional[List[str]] = None) -> CanonicalDialogueUnit:
        clean_content = UniversalContextEnvelope.sanitize(content)
        return CanonicalDialogueUnit(
            role=role,
            content=clean_content,
            source_model=source_model,
            domain=domain,
            importance_weight=importance,
            extracted_facts=facts or []
        )

    @classmethod
    def compile_for_model(
        cls,
        cdus: List[CanonicalDialogueUnit],
        target_model: str,
        target_domain: str,
        injected_facts: Optional[List[str]] = None,
        max_turns: int = 6
    ) -> List[Dict[str, str]]:
        """
        Synthesizes conversation history into the target model's optimal input sequence.
        Seamlessly normalizes across Gemma, Qwen, and Llama families.
        """
        # Tail slice of recent turns
        recent_cdus = cdus[-max_turns:] if len(cdus) > max_turns else cdus

        # System message incorporating specialist instructions and cross-model memory
        system_prompt = (
            f"You are a specialized offline AI assistant for the {target_domain.upper()} domain.\n"
            f"Active Model: {target_model}.\n"
            "Provide rigorous, accurate, and concise reasoning. When writing code or math, be exact."
        )

        if injected_facts:
            facts_block = "\n".join([f"- {cls.sanitize(f)}" for f in injected_facts])
            system_prompt += f"\n\n[RETRIEVED CROSS-MODEL CONTEXT]:\n{facts_block}\n"

        messages: List[Dict[str, str]] = [
            {"role": "system", "content": system_prompt}
        ]

        # Append sanitized turns
        for unit in recent_cdus:
            # If the unit was generated by a different model family, annotate provenance
            content = unit.content
            if unit.role == "assistant" and unit.source_model != target_model:
                content = f"[Context from prior {unit.domain} specialist ({unit.source_model})]:\n{content}"

            messages.append({
                "role": unit.role,
                "content": content
            })

        return messages
